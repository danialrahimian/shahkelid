"use strict";

/**
 * Removes every record that was generated or hand-made for testing, so the
 * dashboard and the CRM report only what actually happened.
 *
 *   npm run purge:generated              # what it would remove
 *   npm run purge:generated -- --write
 *   npm run purge:generated -- --write --include-staff-orders
 *
 * A report built on invented orders is worse than no report: it looks exactly
 * like a real one and every figure on it is wrong. There is no way to tell by
 * looking at a chart whether the money behind it existed.
 *
 * Everything removed is written to a JSON file first, and the path is printed.
 * That file is a plain export of the documents as they stood, so a mistake
 * here is recoverable rather than final.
 *
 * What goes, and why each rule is drawn where it is:
 *
 *   1. Accounts generated by `seed:sales`, matched by their marker domain.
 *   2. Accounts the front-end test suite registered, matched by the exact
 *      shape its `uniqueCredentials()` helper produces.
 *   3. Orders belonging to either of those.
 *   4. Orders naming a plan that is not in the catalogue -- "Yearly2",
 *      "test test" and the like, which exist only because somebody typed
 *      them into the admin form while trying it out.
 *   5. With `--include-staff-orders`, orders placed by an admin, moderator or
 *      owner. A staff member buying ten copies of a plan from their own store
 *      is exercising the checkout, not making a sale. It is a flag rather
 *      than a rule because at a small company the owner may genuinely be a
 *      customer, and that is not a call this script can make.
 *   6. Accounts at example.com with no orders left, no privileges and nothing
 *      else about them -- what a manual probe through the sign-up form leaves
 *      behind. Judged after the orders are decided, so an account is only
 *      "empty" once its test orders have gone.
 *
 * Privileged accounts themselves are never removed, whatever their email
 * looks like: they are how people sign in, and locking somebody out of their
 * own admin panel to tidy a statistic is not a trade worth making.
 */

const fs = require("node:fs/promises");
const path = require("node:path");
const mongoose = require("mongoose");

const config = require("../src/config");
const { User } = require("../src/components/users/user.model");
const { Order } = require("../src/components/orders/order.model");
const { Product } = require("../src/components/products/product.model");
const { CustomerRecord } = require("../src/components/crm/crm.model");

/** Accounts `seed:sales` created. */
const SEED_SALES_EMAIL = /@seed-sales\.example$/;

/** Exactly what the front-end suite's `uniqueCredentials()` builds. */
const FIXTURE_EMAIL = /^t_[a-z0-9]{8}@example\.com$/;

/** The domain reserved for testing, so never a real customer. */
const PROBE_EMAIL = /@example\.com$/;

const money = (value) => "$" + Math.round(value).toLocaleString("en-US");

const main = async () => {
  const write = process.argv.includes("--write");
  const includeStaffOrders = process.argv.includes("--include-staff-orders");

  await mongoose.connect(config.database.uri);

  const [users, orders, products] = await Promise.all([
    User.find().lean(),
    Order.find().lean(),
    Product.find().select("name").lean(),
  ]);

  const catalogue = new Set(products.map((product) => product.name));
  const userById = new Map(users.map((user) => [String(user._id), user]));

  // -------------------------------------------------- 1 & 2: generated accounts

  const generatedReason = (user) => {
    // A role is a login somebody depends on.
    if (user.role !== "user") return null;
    if (SEED_SALES_EMAIL.test(user.email)) return "generated by seed:sales";
    if (FIXTURE_EMAIL.test(user.email)) return "front-end test fixture";
    return null;
  };

  const generated = new Map();
  for (const user of users) {
    const reason = generatedReason(user);
    if (reason) generated.set(String(user._id), reason);
  }

  // ------------------------------------------------------- 3, 4 & 5: orders

  const orderReason = (order) => {
    const ownerId = String(order.user?.userId);

    if (generated.has(ownerId)) return "belongs to a generated account";

    const items = order.items ?? [];
    if (items.length === 0) return "has no lines at all";

    const unknown = [
      ...new Set(
        items
          .map((item) => item.name)
          .filter((name) => !catalogue.has(name)),
      ),
    ];
    if (unknown.length > 0) {
      return `names a plan that is not in the catalogue: ${unknown.join(", ")}`;
    }

    if (includeStaffOrders) {
      const owner = userById.get(ownerId);
      if (owner && owner.role !== "user") {
        return `placed by ${owner.role} "${owner.username}" from their own store`;
      }
    }

    return null;
  };

  const doomedOrders = [];
  const survivingOrders = [];
  for (const order of orders) {
    const reason = orderReason(order);
    if (reason) doomedOrders.push({ order, reason });
    else survivingOrders.push(order);
  }

  // ------------------------------------------------ 6: accounts left empty
  // Judged against the orders that survive, not the ones that started out
  // there. An account whose only purchase was a test purchase is empty once
  // that purchase has gone, and counting it as a buyer would keep it.

  const realBuyers = new Set(
    survivingOrders.map((order) => String(order.user?.userId)).filter(Boolean),
  );

  const doomedUsers = [];
  for (const user of users) {
    const id = String(user._id);

    const reason =
      generated.get(id) ??
      (user.role === "user" &&
      PROBE_EMAIL.test(user.email) &&
      !realBuyers.has(id)
        ? "empty probe account at example.com"
        : null);

    if (reason) doomedUsers.push({ user, reason });
  }

  const doomedUserIds = doomedUsers.map((entry) => entry.user._id);
  const doomedUserIdSet = new Set(doomedUserIds.map(String));

  // ------------------------------------------------------------- report

  const byReason = new Map();
  for (const { reason } of doomedUsers) {
    byReason.set(reason, (byReason.get(reason) ?? 0) + 1);
  }

  console.log(`ACCOUNTS: ${doomedUsers.length} of ${users.length} would go`);
  for (const [reason, count] of byReason) {
    console.log(`  ${String(count).padStart(4)}  ${reason}`);
  }

  const survivors = users.filter(
    (user) => !doomedUserIdSet.has(String(user._id)),
  );
  console.log(`\n  ${survivors.length} would remain:`);
  for (const user of survivors) {
    console.log(
      `    ${user.role.padEnd(9)} ${user.username.padEnd(20)} ${user.email}`,
    );
  }

  const doomedRevenue = doomedOrders
    .filter((entry) => entry.order.status === "paid")
    .reduce((sum, entry) => sum + entry.order.totalPrice, 0);

  console.log(
    `\nORDERS: ${doomedOrders.length} of ${orders.length} would go, carrying ${money(doomedRevenue)} of paid revenue that never happened.`,
  );

  // The hand-made ones are worth naming individually; the generated ones are
  // hundreds of near-identical rows and only the count means anything.
  const handMade = doomedOrders.filter(
    (entry) => !entry.reason.startsWith("belongs to"),
  );
  if (handMade.length > 0) {
    console.log(`\n  ${handMade.length} of them were made by hand:`);
    for (const { order, reason } of handMade) {
      console.log(
        `    ${String(order.status).padEnd(8)} ${money(order.totalPrice).padStart(9)}  ${String(order.user?.username).padEnd(14)}  ${reason}`,
      );
    }
  }

  const survivingRevenue = survivingOrders
    .filter((order) => order.status === "paid")
    .reduce((sum, order) => sum + order.totalPrice, 0);

  console.log(
    `\n  ${survivingOrders.length} orders would remain, worth ${money(survivingRevenue)} in real paid revenue.`,
  );

  if (!includeStaffOrders) {
    const staffOrders = survivingOrders.filter((order) => {
      const owner = userById.get(String(order.user?.userId));
      return owner && owner.role !== "user";
    });
    if (staffOrders.length > 0) {
      console.log(
        `\n  Note: ${staffOrders.length} of those were placed by staff from your own store.`,
      );
      console.log("  Pass --include-staff-orders to treat those as tests too.");
    }
  }

  if (doomedUsers.length === 0 && doomedOrders.length === 0) {
    console.log("\nNothing to remove.");
    await mongoose.disconnect();
    return;
  }

  if (!write) {
    console.log("\nNothing written. Re-run with --write to apply.");
    await mongoose.disconnect();
    return;
  }

  // -------------------------------------------------------------- apply

  const records = await CustomerRecord.find({
    userId: { $in: doomedUserIds },
  }).lean();

  // Written before a single document is removed, so a mistake here costs a
  // restore rather than the data.
  const directory = path.join(__dirname, "..", "backups");
  await fs.mkdir(directory, { recursive: true });

  const file = path.join(
    directory,
    `purge-${new Date().toISOString().replace(/[:.]/g, "-")}.json`,
  );

  await fs.writeFile(
    file,
    JSON.stringify(
      {
        purgedAt: new Date().toISOString(),
        includeStaffOrders,
        users: doomedUsers.map((entry) => ({
          reason: entry.reason,
          document: entry.user,
        })),
        orders: doomedOrders.map((entry) => ({
          reason: entry.reason,
          document: entry.order,
        })),
        customerRecords: records,
      },
      null,
      2,
    ),
    "utf8",
  );

  console.log(`\nBacked up to ${file}`);

  const removedOrders = await Order.deleteMany({
    _id: { $in: doomedOrders.map((entry) => entry.order._id) },
  });
  const removedRecords = await CustomerRecord.deleteMany({
    userId: { $in: doomedUserIds },
  });
  const removedUsers = await User.deleteMany({ _id: { $in: doomedUserIds } });

  console.log(
    `Removed ${removedUsers.deletedCount} accounts, ${removedOrders.deletedCount} orders and ${removedRecords.deletedCount} CRM records.`,
  );

  await mongoose.disconnect();
};

main().catch(async (error) => {
  console.error(error.message);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
