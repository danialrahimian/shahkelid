import { ChevronRight } from "lucide-react";
import { motion } from "motion/react";
import { Link, Outlet, useLocation } from "react-router";

import { AppErrorBoundary } from "@/components/errors/error-fallback";
import { AppSidebar } from "@/components/layouts/app-sidebar";
import { ModeToggle } from "@/components/layouts/mode-toggle";
import {
  DASHBOARD_LINKS,
  isDashboardLinkActive,
} from "@/components/layouts/nav-links";
import { Separator } from "@/components/ui/separator";
import {
  SidebarInset,
  SidebarProvider,
  SidebarTrigger,
} from "@/components/ui/sidebar";
import { paths } from "@/config/paths";

/**
 * The frame of the staff area: a sidebar, a slim header, and the page.
 *
 * It replaces the public navigation bar rather than sitting under it. The
 * sidebar is fixed to the full height of the window, and a floating bar on top
 * of it would cover its header and fight it for the same edge of the screen.
 * The way back to the store is in the sidebar instead.
 */

/**
 * Whether the sidebar was left open last time.
 *
 * The vendored sidebar writes this cookie on every toggle but never reads it
 * back, because upstream expects a server to. Reading it here means a
 * collapsed sidebar stays collapsed across a reload. The name has to match
 * the one in `components/ui/sidebar.tsx`, which is regenerated by the shadcn
 * CLI and so is not edited to export it.
 */
const wasSidebarOpen = () => {
  const stored = document.cookie
    .split("; ")
    .find((entry) => entry.startsWith("sidebar_state="))
    ?.split("=")[1];

  return stored !== "false";
};

/** Where the reader is, as a trail: Dashboard › Customers › Customer. */
const Breadcrumb = ({ pathname }: { pathname: string }) => {
  const section = DASHBOARD_LINKS.find((link) =>
    isDashboardLinkActive(link, pathname),
  );

  // Beneath a section rather than on it: one customer, one product.
  const isDetail =
    section !== undefined && !section.exact && pathname !== section.path;

  const crumbs: { label: string; to?: string }[] = [
    { label: "Dashboard", to: paths.dashboard.getHref() },
  ];
  if (section) {
    crumbs.push({ label: section.label, to: isDetail ? section.to : undefined });
  }
  if (isDetail && section?.detailLabel) {
    crumbs.push({ label: section.detailLabel });
  }

  return (
    <nav aria-label="Breadcrumb" className="min-w-0">
      <ol className="flex min-w-0 items-center gap-1.5 text-sm text-muted-foreground">
        {crumbs.map((crumb, index) => {
          const isLast = index === crumbs.length - 1;

          return (
            <li key={crumb.label} className="flex min-w-0 items-center gap-1.5">
              {index > 0 ? (
                <ChevronRight aria-hidden className="size-3.5 shrink-0" />
              ) : null}

              {isLast || !crumb.to ? (
                <span
                  aria-current={isLast ? "page" : undefined}
                  className={
                    isLast ? "truncate font-medium text-foreground" : "truncate"
                  }
                >
                  {crumb.label}
                </span>
              ) : (
                // The root crumb is hidden on a phone, where the header has
                // room for one label and the current page is the useful one.
                <Link
                  to={crumb.to}
                  className={
                    "truncate transition-colors hover:text-foreground " +
                    (index === 0 ? "hidden sm:inline" : "")
                  }
                >
                  {crumb.label}
                </Link>
              )}
            </li>
          );
        })}
      </ol>
    </nav>
  );
};

const DashboardLayout = () => {
  const { pathname } = useLocation();

  return (
    <SidebarProvider defaultOpen={wasSidebarOpen()}>
      <AppSidebar />

      <SidebarInset className="min-w-0">
        <header className="sticky top-0 z-10 flex h-14 shrink-0 items-center gap-2 border-b border-border/60 bg-background/80 px-4 backdrop-blur md:rounded-t-xl">
          <SidebarTrigger className="-ml-1" />
          <Separator orientation="vertical" className="mr-1 data-[orientation=vertical]:h-4" />
          <Breadcrumb pathname={pathname} />

          <div className="ml-auto">
            <ModeToggle />
          </div>
        </header>

        {/* Scoped to the page, so a screen that throws leaves the sidebar
            working and the reader can go somewhere else. */}
        <AppErrorBoundary resetKeys={[pathname]}>
          <motion.div
            key={pathname}
            initial={{ opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.3, ease: [0.22, 1, 0.36, 1] }}
            className="min-w-0 flex-1 p-4 md:p-6"
          >
            <Outlet />
          </motion.div>
        </AppErrorBoundary>
      </SidebarInset>
    </SidebarProvider>
  );
};

export default DashboardLayout;
