-- Transactional outbox. Written in the same transaction as the change it
-- announces; a relay moves unpublished rows onto the queue. If Redis is down,
-- the rows wait here instead of being lost.
create table outbox_events (
  id             bigint generated always as identity primary key,
  topic          text not null,             -- 'subscription.provision'
  aggregate_type text not null,
  aggregate_id   uuid not null,
  payload        jsonb not null default '{}',
  created_at     timestamptz not null default now(),
  published_at   timestamptz,
  attempts       integer not null default 0,
  last_error     text
);
create index outbox_unpublished_idx on outbox_events (id) where published_at is null;

-- Things that look wrong, for a person to judge: concurrent-use spikes,
-- repeated trial attempts, suspicious receipts.
create type risk_status as enum ('open', 'dismissed', 'confirmed');

create table risk_flags (                                               -- [later]
  id                  uuid primary key default gen_random_uuid(),
  entity_type         text not null,
  entity_id           uuid not null,
  kind                text not null,
  severity            smallint not null check (severity between 1 and 3),
  details             jsonb not null default '{}',
  status              risk_status not null default 'open',
  reviewed_by_user_id uuid references users (id) on delete set null,
  reviewed_at         timestamptz,
  created_at          timestamptz not null default now()
);
create index risk_flags_open_idx   on risk_flags (created_at desc) where status = 'open';
create index risk_flags_entity_idx on risk_flags (entity_type, entity_id);

-- Moving a group of customers from one server to another, tracked so a
-- half-finished move can be resumed rather than guessed at.
create type migration_status as enum ('pending', 'running', 'completed', 'failed', 'cancelled');

create table server_migrations (                                        -- [later]
  id             uuid primary key default gen_random_uuid(),
  from_server_id uuid not null references servers (id) on delete restrict,
  to_server_id   uuid not null references servers (id) on delete restrict,
  status         migration_status not null default 'pending',
  total_count    integer not null default 0,
  done_count     integer not null default 0,
  failed_count   integer not null default 0,
  created_by     uuid references users (id) on delete set null,
  created_at     timestamptz not null default now(),
  finished_at    timestamptz,
  check (from_server_id <> to_server_id)
);
