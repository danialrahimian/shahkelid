create type traffic_reset as enum ('no_reset', 'daily', 'weekly', 'monthly');

-- Plans are volume and time. A null volume is an unlimited plan.
-- Never deleted once sold: orders and subscriptions point at them. Archived.
create table plans (
  id               uuid primary key default gen_random_uuid(),
  slug             text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name             text not null,
  description      text not null default '',
  data_limit_bytes bigint check (data_limit_bytes is null or data_limit_bytes > 0),
  duration_days    integer not null check (duration_days between 1 and 3650),
  device_limit     integer check (device_limit is null or device_limit between 1 and 100),
  traffic_reset    traffic_reset not null default 'no_reset',
  price_toman      bigint not null check (price_toman >= 0),
  is_trial         boolean not null default false,
  is_public        boolean not null default true,  -- false: resellers / staff only
  is_active        boolean not null default true,
  sort_order       integer not null default 0,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  archived_at      timestamptz,
  check (not is_trial or price_toman = 0)
);
-- At most one free-trial plan on offer at a time.
create unique index plans_single_trial_idx on plans (is_trial)
  where is_trial and is_active and archived_at is null;

-- How a plan is expressed on each panel: which groups (inbounds) it grants.
create table plan_panel_settings (
  plan_id          uuid not null references plans (id) on delete cascade,
  panel_id         uuid not null references panels (id) on delete cascade,
  group_ids        integer[] not null default '{}',
  user_template_id integer,
  primary key (plan_id, panel_id)
);

