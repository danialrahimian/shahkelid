-- identity                                                             [MVP]
-- ============================================================================

create type user_status as enum ('active', 'suspended', 'deleted');

create table users (
  id                  uuid primary key default gen_random_uuid(),
  -- case-insensitive, so Ali@x.com and ali@x.com are one account
  email               citext not null unique,
  -- gmail dots and +tags stripped; what free-trial abuse is checked against
  email_normalized    text not null,
  email_verified_at   timestamptz,
  -- null for an account that only ever signs in with an emailed code
  password_hash       text,
  display_name        text not null default '' check (char_length(display_name) <= 80),
  locale              text not null default 'fa' check (locale in ('fa', 'en')),
  status              user_status not null default 'active',
  avatar_file_id      uuid,                       -- fk added after files
  telegram_user_id    bigint unique,
  telegram_username   text,
  referral_code       text not null unique,
  referred_by_user_id uuid references users (id) on delete set null,
  -- TOTP secret, AES-GCM encrypted with the app key; never stored in clear
  totp_secret_enc     bytea,
  totp_enabled_at     timestamptz,
  last_login_at       timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  deleted_at          timestamptz,
  check (referred_by_user_id is null or referred_by_user_id <> id)
);
create index users_email_normalized_idx on users (email_normalized);
create index users_referred_by_idx      on users (referred_by_user_id) where referred_by_user_id is not null;
create index users_created_at_idx       on users (created_at);

-- One-time codes for signing in when the authenticator is lost.
create table user_recovery_codes (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references users (id) on delete cascade,
  code_hash  text not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);
create index user_recovery_codes_user_idx on user_recovery_codes (user_id);

-- Tokens for machine callers: the Telegram bot, reseller API access.
-- Only the hash is stored; the token is shown once, at creation.
create table api_tokens (                                                -- [later]
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid references users (id) on delete cascade,   -- null: a system token
  name         text not null,
  token_hash   text not null unique,
  scopes       text[] not null default '{}',
  last_used_at timestamptz,
  expires_at   timestamptz,
  revoked_at   timestamptz,
  created_by   uuid references users (id) on delete set null,
  created_at   timestamptz not null default now()
);

