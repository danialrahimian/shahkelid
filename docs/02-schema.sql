-- ============================================================================
-- ledger: double-entry money records                                   [MVP]
--
-- Every movement of money is one transaction of two or more entries that sum
-- to zero. An account's balance is the sum of its entries.
--
-- Sign convention: money flows FROM negative entries TO positive ones.
--   customer pays 100 for a plan by zarinpal:  gateway_zarinpal -100, revenue +100
--   ... with a 20 discount on a 120 plan:      gateway_zarinpal -100, discounts -20, revenue +120
--   customer tops up their wallet by 100:      gateway_zarinpal -100, customer_wallet +100
--   customer buys a 100 plan from the wallet:  customer_wallet -100, revenue +100
-- System accounts may go negative. A customer's wallet, a reseller's credit
-- and a commission balance may not: that check is what makes spending the
-- same money twice impossible, even with two purchases at the same instant.
--
-- Built in phase 1 even though the wallet screen comes later, so revenue is
-- on the ledger from the first sale and there is nothing to backfill.
-- ============================================================================

create type ledger_account_kind as enum (
  'customer_wallet', 'reseller_credit', 'commission_balance',   -- per user
  'revenue', 'discounts', 'refunds', 'adjustments',              -- system
  'gateway_zarinpal', 'gateway_card',                            -- system
  'gateway_nowpayments', 'gateway_usdt_tron'                     -- system
);

create table ledger_accounts (
  id            uuid primary key default gen_random_uuid(),
  kind          ledger_account_kind not null,
  user_id       uuid references users (id) on delete restrict,
  balance_toman bigint not null default 0,
  created_at    timestamptz not null default now(),
  -- per-user kinds belong to a user; system kinds belong to nobody
  check ((kind in ('customer_wallet', 'reseller_credit', 'commission_balance')) = (user_id is not null)),
  check (kind not in ('customer_wallet', 'reseller_credit', 'commission_balance') or balance_toman >= 0),
  -- one account of each kind per user, and exactly one of each system kind
  unique nulls not distinct (kind, user_id)
);

create type ledger_tx_kind as enum (
  'order_payment', 'wallet_topup', 'wallet_purchase', 'refund',
  'commission_accrual', 'commission_payout', 'reseller_credit_topup',
  'manual_adjustment'
);

create table ledger_transactions (
  id                 uuid primary key default gen_random_uuid(),
  kind               ledger_tx_kind not null,
  reference_type     text,              -- 'payment', 'order', 'commission'
  reference_id       uuid,
  memo               text not null default '',
  created_by_user_id uuid references users (id) on delete set null,
  -- one ledger posting per business event, however many times it is retried
