-- Permission strings ("payments:approve") are defined in code, where the
-- routes that check them live. Roles are data, so they can be edited.
create table roles (
  id           uuid primary key default gen_random_uuid(),
  key          text not null unique check (key ~ '^[a-z][a-z0-9_]*$'),
  name         text not null,
  description  text not null default '',
  is_system    boolean not null default false,  -- seeded roles cannot be deleted
  requires_2fa boolean not null default true,
  created_at   timestamptz not null default now()
);

create table role_permissions (
  role_id    uuid not null references roles (id) on delete cascade,
  permission text not null check (permission ~ '^[a-z_]+:[a-z_]+$'),
  primary key (role_id, permission)
);

-- A customer has no rows here. Staff have one or more roles.
create table user_roles (
  user_id    uuid not null references users (id) on delete cascade,
  role_id    uuid not null references roles (id) on delete restrict,
  granted_by uuid references users (id) on delete set null,
  granted_at timestamptz not null default now(),
  primary key (user_id, role_id)
);

create type actor_kind as enum ('customer', 'staff', 'reseller', 'system', 'bot');

-- Append-only. The trigger below refuses updates and deletes, so a staff
-- member with database access through the app cannot tidy away what they did.
create table audit_logs (
  id            bigint generated always as identity primary key,
  occurred_at   timestamptz not null default now(),
  actor_kind    actor_kind not null,
  actor_user_id uuid references users (id) on delete set null,
  action        text not null,              -- 'subscription.reset_usage'
  entity_type   text not null,              -- 'subscription'
  entity_id     text,
  before        jsonb,
  after         jsonb,
  ip            inet,
  user_agent    text,
  request_id    text
);
create index audit_logs_entity_idx on audit_logs (entity_type, entity_id, occurred_at desc);
create index audit_logs_actor_idx  on audit_logs (actor_user_id, occurred_at desc);
create index audit_logs_time_idx   on audit_logs (occurred_at);

create function refuse_change() returns trigger language plpgsql as $$
begin
  raise exception '% is append-only', tg_table_name using errcode = 'insufficient_privilege';
end $$;

create trigger audit_logs_append_only
  before update or delete on audit_logs
  for each row execute function refuse_change();

