create type subscription_status as enum (
  'provisioning',         -- paid, not yet on the panel
  'provisioning_failed',  -- retries exhausted: staff alerted, money kept
  'on_hold',              -- created, clock starts on first connection
  'active',
  'limited',              -- volume used up
  'expired',
  'disabled',             -- turned off by staff
  'deleted'
);

create table subscriptions (
  id                     uuid primary key default gen_random_uuid(),
  user_id                uuid not null references users (id) on delete restrict,
  reseller_user_id       uuid references users (id) on delete restrict,   -- [later]
  plan_id                uuid not null references plans (id) on delete restrict,
  panel_id               uuid not null references panels (id) on delete restrict,
  server_id              uuid references servers (id) on delete restrict,
  -- derived from the subscription id, never random: a retried create finds
  -- the user the lost attempt made instead of making a second one
  panel_username         text not null,
  panel_user_id          integer,
  status                 subscription_status not null default 'provisioning',
  is_trial               boolean not null default false,
  -- the limits currently in force, which change with renewals and top-ups
  data_limit_bytes       bigint check (data_limit_bytes is null or data_limit_bytes > 0),
  device_limit           integer,
  expires_at             timestamptz,
  starts_on_first_use    boolean not null default false,
  -- snapshot from the panel; the panel stays the source of truth for usage
  used_bytes             bigint not null default 0 check (used_bytes >= 0),
  lifetime_used_bytes    bigint not null default 0 check (lifetime_used_bytes >= 0),
  online_at              timestamptz,
  last_synced_at         timestamptz,
  -- the customer's link is /s/{access_token} on our domain, proxied to the panel
  access_token           text not null unique,
  panel_subscription_url text,
  auto_renew             boolean not null default false,              -- [later]
  provisioned_at         timestamptz,
  last_error             text,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  unique (panel_id, panel_username),
  unique (panel_id, panel_user_id)
);
create index subscriptions_user_idx     on subscriptions (user_id, created_at desc);
create index subscriptions_reseller_idx on subscriptions (reseller_user_id) where reseller_user_id is not null;
-- the reminder scan: live subscriptions ordered by expiry
create index subscriptions_expiry_idx   on subscriptions (expires_at)
  where status in ('active', 'on_hold', 'limited');
-- the placement count: how many live subscriptions each server carries
create index subscriptions_server_idx   on subscriptions (server_id)
  where status in ('provisioning', 'on_hold', 'active', 'limited');
create index subscriptions_status_idx   on subscriptions (status) where status in ('provisioning', 'provisioning_failed');

-- Everything that ever happened to a subscription, including what the system
-- did on its own. Support reads this next to a ticket.
create table subscription_events (
  id              bigint generated always as identity primary key,
  subscription_id uuid not null references subscriptions (id) on delete cascade,
  kind            text not null,   -- created, renewed, upgraded, reset_usage, added_data, ...
  actor_kind      actor_kind not null,
  actor_user_id   uuid references users (id) on delete set null,
  order_id        uuid,            -- fk added after orders
  details         jsonb not null default '{}',
  created_at      timestamptz not null default now()
);
create index subscription_events_idx on subscription_events (subscription_id, id desc);

-- "Each reminder once per cycle." A renewal starts a new cycle (a new
-- expiry), so the same reminder can fire again for the new term.
create table subscription_alerts_sent (
  subscription_id uuid not null references subscriptions (id) on delete cascade,
  alert           text not null check (alert in ('expiry_3d', 'expiry_1d', 'usage_80', 'usage_100')),
  cycle_key       text not null,
  sent_at         timestamptz not null default now(),
  primary key (subscription_id, alert, cycle_key)
);

-- Traffic per day, for charts and analytics. At ~10k subscriptions this is
-- a few million rows a year, well inside what one table handles.
create table usage_daily (                                              -- [later]
  subscription_id uuid not null references subscriptions (id) on delete cascade,
  day             date not null,
  used_bytes      bigint not null check (used_bytes >= 0),
  primary key (subscription_id, day)
);

-- One free trial per person. Each identity column is unique on its own, so a
-- second trial needs a new email AND a new Telegram account AND passes the
-- ip / fingerprint checks the app makes against the indexes below.
create table trial_claims (                                             -- [later]
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid not null unique references users (id) on delete cascade,
  email_normalized text not null unique,
  telegram_user_id bigint unique,
  ip               inet,
  fingerprint      text,
  subscription_id  uuid unique references subscriptions (id) on delete set null,
  claimed_at       timestamptz not null default now()
);
create index trial_claims_ip_idx          on trial_claims (ip);
create index trial_claims_fingerprint_idx on trial_claims (fingerprint);

