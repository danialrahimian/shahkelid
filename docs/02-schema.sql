create type discount_kind as enum ('percent', 'fixed');

create table discount_codes (                                           -- [later]
  id                 uuid primary key default gen_random_uuid(),
  code               citext not null unique,
  kind               discount_kind not null,
  value              integer not null check (value > 0),   -- percent, or toman
  max_discount_toman bigint check (max_discount_toman > 0),
  min_order_toman    bigint check (min_order_toman >= 0),
  starts_at          timestamptz,
  ends_at            timestamptz,
  max_redemptions    integer check (max_redemptions > 0),
  max_per_user       integer check (max_per_user > 0),
  restricted_user_id uuid references users (id) on delete cascade,
  first_order_only   boolean not null default false,
  -- incremented under a row lock when an order is PAID, not when it is
  -- created, so abandoned checkouts do not use up a limited code
  redemptions_count  integer not null default 0 check (redemptions_count >= 0),
  is_active          boolean not null default true,
  created_by         uuid references users (id) on delete set null,
  created_at         timestamptz not null default now(),
  check (kind <> 'percent' or value <= 100),
  check (ends_at is null or starts_at is null or ends_at > starts_at),
  check (max_redemptions is null or redemptions_count <= max_redemptions)
);

create table discount_code_plans (                                      -- [later]
  code_id uuid not null references discount_codes (id) on delete cascade,
  plan_id uuid not null references plans (id) on delete cascade,
  primary key (code_id, plan_id)
);

create type order_kind as enum (
  'new', 'renewal', 'upgrade', 'add_data', 'add_days', 'wallet_topup'
);
create type order_status as enum (
  'pending', 'paid', 'fulfilled', 'failed', 'cancelled', 'expired', 'refunded'
);

create table orders (
  id                uuid primary key default gen_random_uuid(),
  number            bigint generated always as identity (start with 100001) unique,
  user_id           uuid not null references users (id) on delete restrict,
  -- staff or a reseller acting for the customer; null when they bought it
  placed_by_user_id uuid references users (id) on delete set null,
  kind              order_kind not null,
  status            order_status not null default 'pending',
  -- renewal / upgrade / add_*: the subscription it changes.
  -- new: the subscription it produced, set once fulfilled.
  subscription_id   uuid references subscriptions (id) on delete restrict,
  subtotal_toman    bigint not null check (subtotal_toman >= 0),
  discount_toman    bigint not null default 0 check (discount_toman >= 0),
  total_toman       bigint not null,
  discount_code_id  uuid references discount_codes (id) on delete restrict,
  idempotency_key   text,
  expires_at        timestamptz not null,   -- an unpaid order lapses
  paid_at           timestamptz,
  fulfilled_at      timestamptz,
  cancelled_at      timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  check (total_toman = subtotal_toman - discount_toman and total_toman >= 0),
  check (kind in ('new', 'wallet_topup') or subscription_id is not null),
  -- a retried POST with the same key returns the first order, not a second
  unique (user_id, idempotency_key)
);
create index orders_user_idx         on orders (user_id, created_at desc);
create index orders_subscription_idx on orders (subscription_id) where subscription_id is not null;
create index orders_pending_idx      on orders (expires_at) where status = 'pending';
create index orders_paid_at_idx      on orders (paid_at) where paid_at is not null;

alter table subscription_events
  add constraint subscription_events_order_fk
  foreign key (order_id) references orders (id) on delete set null;

create table order_items (
  id               uuid primary key default gen_random_uuid(),
  order_id         uuid not null references orders (id) on delete cascade,
  plan_id          uuid references plans (id) on delete restrict,   -- null for wallet top-ups
  -- the plan exactly as sold: name, volume, days, devices, price. Reports and
  -- invoices read this, so editing a plan never rewrites a past sale.
  plan_snapshot    jsonb not null default '{}',
  quantity         integer not null default 1 check (quantity between 1 and 1000),
  unit_price_toman bigint not null check (unit_price_toman >= 0),
  total_toman      bigint not null,
  check (total_toman = unit_price_toman * quantity)
);
create index order_items_order_idx on order_items (order_id);
create index order_items_plan_idx  on order_items (plan_id);

create table discount_redemptions (                                     -- [later]
  id           uuid primary key default gen_random_uuid(),
  code_id      uuid not null references discount_codes (id) on delete restrict,
  user_id      uuid not null references users (id) on delete restrict,
  order_id     uuid not null unique references orders (id) on delete restrict,
  amount_toman bigint not null check (amount_toman > 0),
  redeemed_at  timestamptz not null default now()
);
create index discount_redemptions_code_user_idx on discount_redemptions (code_id, user_id);

-- Crypto is two methods, not one. They reach the same wallet by different
-- routes, fail in different ways and are reconciled against different
-- records, so each gets its own method and its own ledger account.
create type payment_method as enum (
  'zarinpal', 'card_transfer', 'nowpayments', 'usdt_tron', 'wallet'
);
create type payment_status as enum (
  'initiated', 'pending', 'pending_review', 'succeeded', 'failed', 'expired', 'refunded'
);

-- One order can have several attempts (a failed card, then a card transfer).
-- At most one of them succeeds: enforced by the index below.
create table payments (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null references orders (id) on delete restrict,
  user_id             uuid not null references users (id) on delete restrict,
  method              payment_method not null,
  status              payment_status not null default 'initiated',
  amount_toman        bigint not null check (amount_toman > 0),
  -- zarinpal authority, card-transfer tracking number, NOWPayments payment
  -- id, or the TRON transaction hash
  provider_reference  text,
  provider_ref_id     text,                -- zarinpal ref_id after verify
  provider_payload    jsonb not null default '{}',
  failure_reason      text,
  reviewed_by_user_id uuid references users (id) on delete set null,
  reviewed_at         timestamptz,
  succeeded_at        timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  check ((status = 'succeeded') = (succeeded_at is not null) or status = 'refunded')
);
-- A second callback for the same payment cannot count twice.
create unique index payments_provider_ref_idx
  on payments (method, provider_reference) where provider_reference is not null;
-- Two payments cannot both settle one order.
create unique index payments_one_success_idx
  on payments (order_id) where status = 'succeeded';
-- The reconcile job and the review queue.
create index payments_open_idx
  on payments (status, created_at) where status in ('initiated', 'pending', 'pending_review');
create index payments_user_idx on payments (user_id, created_at desc);

-- The cards shown to customers for card-to-card transfer.
create table payment_cards (
  id          uuid primary key default gen_random_uuid(),
  label       text not null,
  bank_name   text not null,
  card_number text not null check (card_number ~ '^[0-9]{16}$'),
  holder_name text not null,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

-- Duplicates are FLAGGED, not rejected. A genuine customer can re-upload the
-- same receipt after a mistake; the accountant sees the flag and decides.
create table card_transfer_receipts (
