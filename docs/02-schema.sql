create type server_status as enum ('online', 'degraded', 'offline', 'maintenance');

-- A server is what customers are placed on, what costs money every month,
-- and what profit is attributed to. In PasarGuard it is a node, and access to
-- it is granted through a group.
create table servers (
  id              uuid primary key default gen_random_uuid(),
  panel_id        uuid not null references panels (id) on delete restrict,
  location_id     uuid not null references locations (id) on delete restrict,
  name            text not null,
  host            text not null,
  panel_node_id   integer,
  panel_group_id  integer,                  -- the group that grants access to it
  capacity_users  integer not null check (capacity_users > 0),
  priority        integer not null default 0,
  accepting_new   boolean not null default true,
  status          server_status not null default 'online',
  last_checked_at timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  archived_at     timestamptz
);
create index servers_panel_idx     on servers (panel_id);
create index servers_placement_idx on servers (priority desc)
  where accepting_new and status = 'online' and archived_at is null;

create table server_health_checks (                                     -- [later]
  id         bigint generated always as identity primary key,
  server_id  uuid not null references servers (id) on delete cascade,
  checked_at timestamptz not null default now(),
  ok         boolean not null,
  latency_ms integer check (latency_ms >= 0),
  error      text
);
create index server_health_checks_idx on server_health_checks (server_id, checked_at desc);

-- Monthly, so a price change does not rewrite last year's profit.
create table server_costs (                                             -- [later]
  id           uuid primary key default gen_random_uuid(),
  server_id    uuid not null references servers (id) on delete restrict,
  month        date not null check (extract(day from month) = 1),
  amount_toman bigint not null check (amount_toman >= 0),
  note         text not null default '',
  created_by   uuid references users (id) on delete set null,
  created_at   timestamptz not null default now(),
  unique (server_id, month)
);

create type incident_severity as enum ('minor', 'major', 'critical');

-- What the public status page shows alongside live health.
create table status_incidents (                                         -- [later]
  id           uuid primary key default gen_random_uuid(),
  title        text not null,
  body         text not null default '',
  severity     incident_severity not null,
  location_ids uuid[] not null default '{}',
