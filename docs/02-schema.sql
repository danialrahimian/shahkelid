-- ============================================================================
-- Stage 2: reference schema (PostgreSQL 16+)
--
-- The design reference for the Drizzle schema that stage 4 writes. It is
-- executable: `cd docs/schema-check && npm install && npm run verify` loads
-- it into a real PostgreSQL (PGlite, in-process, nothing to install system-
-- wide) and tries every thing the design says the database refuses.
-- Section tags say which phase builds it:
--   [MVP]    phase 1
--   [later]  a later phase; designed now so phase 1 does not paint over it
--
-- Conventions
--   * ids are uuid, generated by the app as UUIDv7 (time-ordered, so index
--     inserts stay append-like; not guessable, so no enumerable ids in URLs).
--     The column default is only a fallback.
--   * human-facing numbers (orders, invoices, tickets) are separate
--     identity columns: short, sequential, printable on a receipt.
--   * money is bigint TOMAN and every such column says so (`_toman`). Never
--     fractional. Zarinpal takes rial; the adapter converts at the boundary.
--   * traffic is bigint BYTES, the unit the VPN panel uses.
--   * every timestamp is timestamptz, stored in UTC.
--   * updated_at is maintained by the application (Drizzle $onUpdate).
-- ============================================================================

create extension if not exists citext;

