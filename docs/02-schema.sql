-- The toman price of USDT, read from Nobitex's public API.
--
-- Nobitex quotes in RIAL; the fetcher divides by ten before storing. Both
-- sides of the book are kept:
--   bid: the best price someone will pay for USDT, i.e. what the business
--        would get converting what it receives. Invoices are quoted on this,
--        so conversion never costs the business money.
--   ask: kept for reference and for the spread shown on the dashboard.
--
-- Crypto checkout is refused when the newest row is older than a few minutes
-- or the market reports itself closed: selling at a stale rate is the one
-- failure this table exists to prevent. Old rows are pruned unless an invoice
-- refers to them.
create table exchange_rates (
  id         bigint generated always as identity primary key,
  source     text not null default 'nobitex',
  asset      text not null default 'USDT',
  bid_toman  bigint not null check (bid_toman > 0),
  ask_toman  bigint not null check (ask_toman > 0),
  fetched_at timestamptz not null default now(),
  check (bid_toman <= ask_toman)
);
create index exchange_rates_latest_idx on exchange_rates (asset, fetched_at desc);

-- One row per crypto quote, for both methods.
--
-- The rate is fixed when the invoice is issued and the invoice expires, so a
-- price swing between quote and payment is not the business's loss.
--
-- NOWPayments: the processor gives each invoice its own deposit address and
-- tells us by signed IPN callback when it is paid. `processor_invoice_id` is
-- their payment id. The callback is only a prompt: the status is re-read from
-- their API before anything is credited, as with Zarinpal's verify.
--
-- Direct USDT on TRON: every invoice pays to the same wallet address, so an
-- incoming transfer is matched to its invoice by EXACT AMOUNT. Each quote gets
-- a few extra micro-units (12.000347 rather than 12) that no other open
-- invoice on that address has. The partial unique index below is what makes
-- that amount unambiguous; closing the invoice (paid or expired) frees it.
create table crypto_invoices (
  payment_id            uuid primary key references payments (id) on delete cascade,
  asset                 text not null default 'USDT',
  network               text not null default 'TRON',
  -- the token contract actually accepted. Checked by address, never by
  -- symbol: anyone can mint a worthless token and name it "USDT".
  token_contract        text not null,
  amount_units          bigint not null check (amount_units > 0),   -- USDT has 6 decimals
  amount_received_units bigint not null default 0 check (amount_received_units >= 0),
  rate_toman_per_asset  bigint not null check (rate_toman_per_asset > 0),
  -- the exact quote used, so any invoice's price can be traced to its source
  exchange_rate_id      bigint not null references exchange_rates (id) on delete restrict,
  pay_address           text not null,
  processor_invoice_id  text unique,                 -- NOWPayments only
  expires_at            timestamptz not null,
  closed_at             timestamptz                  -- paid, expired or cancelled
);
-- No two open invoices may wait for the same amount at the same address.
create unique index crypto_invoices_open_amount_idx
  on crypto_invoices (network, pay_address, amount_units) where closed_at is null;
create index crypto_invoices_open_idx on crypto_invoices (expires_at) where closed_at is null;

